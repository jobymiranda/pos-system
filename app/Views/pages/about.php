    <h1>About SimplePOS</h1>

    <p>
        SimplePOS is the first version of a basic point-of-sale
        system developed as a CodeIgniter 4 laboratory exercise.
    </p>
</section>

<section class="content-panel">
    <h2>Purpose</h2>

    <p>
        The project demonstrates how CodeIgniter uses routes,
        controllers, and views to convert browser requests into
        complete web pages.
    </p>

    <h2>MVC structure</h2>

    <ul>
        <li>
            <strong>Routes</strong> connect URLs to controller methods.
        </li>

        <li>
            <strong>Controllers</strong> prepare data and choose views.
        </li>

        <li>
            <strong>Views</strong> create the HTML shown in the browser.
        </li>
        
        <li>
             <strong>Models</strong> retrieve records from MySQL.
        </li>
    </ul>

     <h2>Database-backed data</h2>

    <p>
    Customer and user records are stored in a MySQL database.
    CodeIgniter Models retrieve the records and pass them to
    the application views.
    </p>
</section>